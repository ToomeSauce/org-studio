#!/usr/bin/env node
/**
 * #1647 — refresh schema/org-studio-schema.json from the real database.
 *
 * Run whenever the schema changes (new column, new table used by promote-path
 * SQL). The sql-schema-guard test validates promote-path SQL against this
 * manifest, so a stale manifest = false failures; refresh it in the same
 * commit as the schema change.
 *
 * Usage: node scripts/refresh-schema-manifest.mjs
 * Reads DATABASE_URL from .env.local (or env).
 */
import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';
import pg from 'pg';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

let dbUrl = process.env.DATABASE_URL;
if (!dbUrl) {
  try {
    const env = readFileSync(join(root, '.env.local'), 'utf-8');
    dbUrl = env.match(/^DATABASE_URL=(.*)$/m)?.[1];
  } catch { /* fall through */ }
}
if (!dbUrl) {
  console.error('DATABASE_URL not found (env or .env.local)');
  process.exit(1);
}

// Tables covered by the guard. Add here when guard scope grows.
const TABLES = [
  'org_studio_projects',
  'org_studio_tasks',
  'org_studio_roadmap_versions',
  'org_studio_comments',
];

const client = new pg.Client(dbUrl);
await client.connect();
const res = await client.query(
  `SELECT table_name, column_name
     FROM information_schema.columns
    WHERE table_name = ANY($1)
    ORDER BY table_name, ordinal_position`,
  [TABLES],
);
await client.end();

const manifest = {};
for (const row of res.rows) {
  (manifest[row.table_name] ??= []).push(row.column_name);
}

for (const t of TABLES) {
  if (!manifest[t] || manifest[t].length === 0) {
    console.error(`Table ${t} returned no columns — refusing to write an empty manifest.`);
    process.exit(1);
  }
}

const outPath = join(root, 'schema', 'org-studio-schema.json');
writeFileSync(outPath, JSON.stringify({
  _comment: 'Generated by scripts/refresh-schema-manifest.mjs (#1647). Do not hand-edit — refresh from the real DB.',
  _generatedAt: new Date().toISOString(),
  tables: manifest,
}, null, 2) + '\n');
console.log(`Wrote ${outPath}`);
for (const [t, cols] of Object.entries(manifest)) {
  console.log(`  ${t}: ${cols.length} columns`);
}
